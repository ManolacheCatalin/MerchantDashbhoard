-- Amounts are in the merchant's reporting_currency; there is no per-transaction currency.
--changeset awin-merchant:002-create-transactions
CREATE TABLE transactions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id BIGINT        NOT NULL,
    amount      NUMERIC(19,2) NOT NULL,
    status      VARCHAR(20)   NOT NULL,
    occurred_at TIMESTAMPTZ   NOT NULL,
    CONSTRAINT fk_transactions_merchant FOREIGN KEY (merchant_id) REFERENCES merchants (id),
    CONSTRAINT ck_transactions_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_transactions_status CHECK (status IN ('PENDING', 'APPROVED', 'DECLINED', 'REFUNDED'))
);

CREATE INDEX ix_transactions_merchant_occurred ON transactions (merchant_id, occurred_at);
