CREATE TABLE todo_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id BIGINT       NOT NULL,
    title       VARCHAR(255) NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_todo_items_merchant FOREIGN KEY (merchant_id) REFERENCES merchants (id),
    CONSTRAINT ck_todo_items_status CHECK (status IN ('OPEN', 'COMPLETED'))
);

-- Matches the open-items query: WHERE merchant_id = ? AND status = 'OPEN' ORDER BY created_at, id
CREATE INDEX ix_todo_items_merchant_status_created ON todo_items (merchant_id, status, created_at, id);
