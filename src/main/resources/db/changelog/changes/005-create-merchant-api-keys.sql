-- Stores only the lower-case hex SHA-256 of a high-entropy random key; never the key itself.
-- One key record per merchant; replacing a key overwrites key_hash (no history).
--changeset awin-merchant:005-create-merchant-api-keys
CREATE TABLE merchant_api_keys (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id BIGINT      NOT NULL,
    key_hash    VARCHAR(64) NOT NULL,
    active      BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_merchant_api_keys_merchant FOREIGN KEY (merchant_id) REFERENCES merchants (id),
    CONSTRAINT uq_merchant_api_keys_merchant UNIQUE (merchant_id),
    CONSTRAINT uq_merchant_api_keys_key_hash UNIQUE (key_hash),
    CONSTRAINT ck_merchant_api_keys_key_hash_format CHECK (key_hash ~ '^[0-9a-f]{64}$')
);
--rollback DROP TABLE merchant_api_keys;
